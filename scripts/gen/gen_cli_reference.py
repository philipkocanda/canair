#!/usr/bin/env python3
"""Generate the per-command CLI reference under docs/reference/cli/ from --help.

The CLI's argparse help is the single source of truth for flags and usage, so we
render it into Markdown rather than hand-maintaining a copy that drifts. Each
top-level `canair <cmd>` becomes docs/reference/cli/<cmd>.md, including every nested
sub-kind at any depth (e.g. `scan range`, `ecu add`, `wican autopid write`).

Usage:
    uv run python scripts/gen/gen_cli_reference.py            # write the pages
    uv run python scripts/gen/gen_cli_reference.py --check     # fail if pages are stale (CI)

Run it after changing any command's parser (add/rename a flag, a new subcommand).
"""

from __future__ import annotations

import argparse
import io
import os
import re
import sys
import tempfile
from contextlib import redirect_stdout
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "docs" / "reference" / "cli"
GENERATED_NOTE = (
    "<!-- GENERATED by scripts/gen/gen_cli_reference.py — do not edit by hand. "
    "Regenerate after changing a command's parser. -->"
)


def _isolate_environment() -> None:
    """Make help output reproducible across machines/CI.

    Some `--help` strings embed config-resolved defaults (e.g. the `--wican`
    default reads `default_wican` from config). Both the user config
    (`$XDG_CONFIG_HOME/canair/config.yaml`) and a legacy gitignored repo-root
    `config.yaml` feed that resolution, so generation would otherwise depend on
    whoever's local config happens to be present (and CI, which has neither,
    would disagree). Force an empty config and clear the relevant env vars so the
    output is identical everywhere.
    """
    tmp = tempfile.mkdtemp(prefix="canair-genref-")
    os.environ["XDG_CONFIG_HOME"] = tmp
    for var in ("CANAIR_PROFILE", "CANAIR_PROFILES_DIR"):
        os.environ.pop(var, None)

    # Neutralize both config sources (user + legacy repo-local) deterministically.
    from canair.config import file as config_file

    config_file.load_config.cache_clear()
    config_file.load_config = lambda: {}  # type: ignore[assignment]

    # --help lists --unsafe only on a terminal; the reference documents every flag.
    from canair.cli.live import parser as live_parser

    live_parser.unsafe_flag_visible = lambda: True  # type: ignore[assignment]


def _format_help(parser: argparse.ArgumentParser) -> str:
    """Capture a parser's --help text (argparse writes to stdout via print_help)."""
    buf = io.StringIO()
    with redirect_stdout(buf):
        parser.print_help()
    return buf.getvalue().rstrip()


def _subparsers_action(parser: argparse.ArgumentParser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _render_command(
    name: str, parser: argparse.ArgumentParser, aliases: list[str] | None = None
) -> str:
    """Render one top-level command (and its nested sub-kinds) to Markdown."""
    lines = [GENERATED_NOTE, "", f"# `canair {name}`", ""]
    if aliases:
        hint = ", ".join(f"`{a}`" for a in aliases)
        lines += [f"*Alias{'es' if len(aliases) > 1 else ''}: {hint}*", ""]
    lines += ["```", _format_help(parser), "```", ""]
    lines += _render_kinds(name, parser, depth=2)
    return "\n".join(lines).rstrip() + "\n"


def _render_kinds(prefix: str, parser: argparse.ArgumentParser, depth: int) -> list[str]:
    """Render every sub-kind of ``parser``, and theirs in turn, one heading level deeper each."""
    sub = _subparsers_action(parser)
    if sub is None:
        return []
    lines: list[str] = []
    # choices maps sub-kind name -> its ArgumentParser (dedup aliases sharing one parser).
    seen: set[int] = set()
    for kind, subparser in sub.choices.items():
        if id(subparser) in seen:
            continue
        seen.add(id(subparser))
        path = f"{prefix} {kind}"
        lines += [f"{'#' * depth} `canair {path}`", ""]
        lines += ["```", _format_help(subparser), "```", ""]
        lines += _render_kinds(path, subparser, depth + 1)
    return lines


def _command_names() -> list[str]:
    """Registered subcommand names, in help-display order.

    A command's *module* name (``COMMAND_NAMES``) is not always its registered
    subcommand ``NAME`` — e.g. the ``import_`` module registers ``import`` (the
    trailing underscore avoids shadowing the ``import`` keyword). The parser
    registers under ``NAME``, so the reference pages must key off ``NAME`` too.
    """
    from canair.cli.commands import iter_command_modules

    return [module.NAME for module in iter_command_modules()]


def _summary(description: str, name: str) -> str:
    """One overview line for a command: its first sentence, as Markdown.

    Takes the first paragraph (a description is hard-wrapped), turns reStructuredText double
    backticks into Markdown code, drops a leading ``canair NAME —`` that the bullet already
    shows and a leading domain tag (``[UDS] …``; each command page states its domain), and cuts
    at the first sentence end.
    """
    text = " ".join((description or "").strip().split("\n\n")[0].split())
    text = text.replace("``", "`")
    if text.startswith("["):
        text = text.split("]", 1)[-1].lstrip()
    text = re.sub(rf"^`canair {re.escape(name)}`\s*[—-]\s*", "", text)
    if text[:1].islower():
        text = text[0].upper() + text[1:]
    sentence = re.match(r"(.+?[.?]['\"]?)(?:\s|$)", text)
    if sentence:
        text = sentence.group(1)
    return text.rstrip(":").rstrip()


def _index_page(names: list[str]) -> str:
    """Rewrite the cli/ index to list the generated per-command pages.

    Commands are grouped under the same categories the top-level ``canair
    --help`` uses (``canair.cli.args.categories``); anything absent from a
    category falls under a trailing "Other" heading, so the two never drift.
    """
    from canair.cli import build_parser
    from canair.cli.args.categories import CATEGORIES, OTHER_TITLE

    parser = build_parser()
    sub = _subparsers_action(parser)
    help_by_name = {}
    if sub is not None:
        for n, p in sub.choices.items():
            help_by_name[n] = _summary(p.description or "", n)

    lines = [
        "# CLI reference",
        "",
        "Every capability is a `canair <subcommand>`. These pages are generated "
        "from each command's `--help` (the source of truth), so they never drift "
        "from the code.",
        "",
        "> Regenerate with `uv run python scripts/gen/gen_cli_reference.py`; CI checks they are current.",
        "",
        "## Commands",
        "",
    ]

    def _bullet(n: str) -> str:
        summary = help_by_name.get(n, "")
        return f"- [`canair {n}`]({n}.md)" + (f" — {summary}" if summary else "")

    available = set(names)
    emitted: set[str] = set()
    for title, group in CATEGORIES:
        members = [n for n in group if n in available]
        if not members:
            continue
        lines += [f"### {title}", ""]
        for n in members:
            lines.append(_bullet(n))
            emitted.add(n)
        lines.append("")

    # Preserve registration order for anything not placed in a category.
    leftover = [n for n in names if n not in emitted]
    if leftover:
        lines += [f"### {OTHER_TITLE}", ""]
        lines += [_bullet(n) for n in leftover]
        lines.append("")

    return "\n".join(lines)


def generate() -> dict[str, str]:
    """Build the full set of {relative_path: content} for the cli/ reference."""
    from canair.cli import build_parser

    parser = build_parser()
    sub = _subparsers_action(parser)
    assert sub is not None, "top-level parser has no subcommands"

    names = _command_names()
    pages: dict[str, str] = {}
    for name in names:
        subparser = sub.choices.get(name)
        if subparser is None:
            continue
        # Alias keys share the canonical name's parser object (argparse aliases).
        aliases = [k for k, v in sub.choices.items() if v is subparser and k != name]
        pages[f"{name}.md"] = _render_command(name, subparser, aliases)
    pages["index.md"] = _index_page(names)
    return pages


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any page differs from what would be generated (CI).",
    )
    args = ap.parse_args(argv)

    _isolate_environment()

    pages = generate()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    stale: list[str] = []
    for rel, content in pages.items():
        path = OUT_DIR / rel
        current = path.read_text() if path.exists() else None
        if current != content:
            stale.append(rel)
            if not args.check:
                path.write_text(content)

    # Remove any stale generated pages no longer produced (except index).
    expected = set(pages) | {"index.md"}
    for path in OUT_DIR.glob("*.md"):
        if path.name not in expected:
            stale.append(path.name)
            if not args.check:
                path.unlink()

    if args.check:
        if stale:
            print(
                "CLI reference is out of date; run "
                "`uv run python scripts/gen/gen_cli_reference.py`. Stale: "
                + ", ".join(sorted(stale)),
                file=sys.stderr,
            )
            return 1
        print("CLI reference is up to date.")
        return 0

    print(f"Wrote {len(pages)} CLI reference page(s) to {OUT_DIR.relative_to(REPO_ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
